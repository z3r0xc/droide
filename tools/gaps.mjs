#!/usr/bin/env node
/**
 * Collect every `TODO(spec <clause>)` marker in the product layer into
 * `docs/gaps.md`, so gaps between a specification and the implementation are
 * reviewable in one place instead of buried in comments.
 *
 *   node tools/gaps.mjs           # rewrite docs/gaps.md
 *   node tools/gaps.mjs --check   # exit 1 when the file is stale (CI)
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const SRC = path.join(ROOT, "src");
const OUT = path.join(ROOT, "docs", "gaps.md");
const MARKER = /TODO\(spec ([^)]*)\)[`:]?\s*(.*)$/;

function walk(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else if (entry.name.endsWith(".ts")) files.push(full);
  }
  return files;
}

const rows = [];
for (const file of walk(SRC).sort()) {
  const lines = fs.readFileSync(file, "utf8").split("\n");
  lines.forEach((line, index) => {
    const match = MARKER.exec(line.trim().replace(/^\*?\s*/, ""));
    if (match === null) return;
    // A marker's note may continue on following comment lines; join them so the
    // table reads as a sentence instead of a truncated fragment.
    let note = match[2];
    for (let next = index + 1; next < lines.length; next += 1) {
      const continuation = (lines[next] ?? "").trim();
      const isCommentLine = (continuation.startsWith("*") && !continuation.startsWith("*/")) || continuation.startsWith("//");
      if (!isCommentLine) break;
      note += ` ${continuation.replace(/^\*+\s*|^\/+\s*/, "")}`;
      if (continuation.endsWith("*/")) break;
    }
    rows.push({
      clause: match[1].trim().replace(/`/g, ""),
      note: note
        .replace(/\*\/\s*$/, "")
        .replace(/`/g, "")
        .replace(/^:\s*/, "")
        .replace(/\s+/g, " ")
        .trim(),
      where: `${path.relative(ROOT, file).split(path.sep).join("/")}:${index + 1}`,
    });
  });
}

rows.sort((left, right) => left.where.localeCompare(right.where));

const byClause = new Map();
for (const row of rows) byClause.set(row.clause, (byClause.get(row.clause) ?? 0) + 1);

const lines = [
  "# Specification gaps",
  "",
  "Generated by `node tools/gaps.mjs` from `TODO(spec …)` markers in `src/`.",
  "Each row is a place where the implementation is narrower than the clause it",
  "cites — never a guess dressed up as behaviour. `npm run gaps:check` fails when",
  "this file is stale.",
  "",
  `Total: **${rows.length}** markers across **${byClause.size}** clauses.`,
  "",
  "| where | clause | missing behaviour |",
  "|---|---|---|",
  ...rows.map((row) => `| \`${row.where}\` | \`${row.clause}\` | ${row.note.replace(/\|/g, "\\|")} |`),
  "",
];

const text = `${lines.join("\n")}`;
const check = process.argv.includes("--check");
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";

if (check) {
  if (current !== text) {
    console.error("docs/gaps.md is stale; run `node tools/gaps.mjs`");
    process.exit(1);
  }
  console.log(`gaps up to date (${rows.length} markers)`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${rows.length} markers)`);
}